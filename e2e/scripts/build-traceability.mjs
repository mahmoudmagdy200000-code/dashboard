#!/usr/bin/env node
// Builds traceability/TRACEABILITY.md: Business Rules v3.4 acceptance cases →
// tests → coverage layer → latest result (from reports/**/results.json when present).
// Usage: node scripts/build-traceability.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(join(ROOT, 'traceability/brc34_acceptance_registry.json'), 'utf8'));
const rules = JSON.parse(readFileSync(join(ROOT, 'traceability/br-v3.4-rule-ids.json'), 'utf8'));

const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith('.spec.ts') ? [p] : [];
});

// 1. Static extraction: test title + traces(layer, ...ids)
const tests = [];
for (const file of walk(join(ROOT, 'tests'))) {
  const src = readFileSync(file, 'utf8');
  const re = /test\(\s*[`'"](.+?)[`'"]\s*,\s*(?:async\s*)?\([^)]*\)\s*=>\s*\{([\s\S]*?)\n\s*\}\);/g;
  for (const m of src.matchAll(re)) {
    const tr = /traces\(\s*([A-Za-z]+|'[^']+')\s*(?:,([^)]*))?\)/.exec(m[2]);
    if (!tr) continue;
    const layerToken = tr[1].replace(/'/g, '');
    const layer = layerToken === 'reviewLayer' ? 'ui-e2e when ASSAB_E2E_UI=true, else api-only' : layerToken;
    const ids = [...(tr[2] ?? '').matchAll(/'([A-Z]+-\d{2})'/g)].map((x) => x[1]);
    tests.push({ file: relative(ROOT, file), title: m[1].replace(/\$\{[^}]+\}/g, '…'), layer, ids, unconditionalBlock: /^\s*traces\([^)]*\);\s*\n\s*blocked\(/m.test(m[2]) });
  }
}

// 2. Latest results (optional)
const results = new Map();
const collect = (suite, file) => {
  for (const s of suite.suites ?? []) collect(s, s.file ?? file);
  for (const sp of suite.specs ?? []) {
    for (const t of sp.tests ?? []) {
      const r = t.results?.at(-1);
      const ann = [...(t.annotations ?? []), ...(r?.annotations ?? [])];
      const blocked = ann.find((a) => a.type === 'BLOCKED');
      const status = r?.status === 'passed' ? 'PASS' : r?.status === 'failed' || r?.status === 'timedOut' ? 'FAIL' : blocked ? 'BLOCKED' : 'NOT_RUN';
      const layer = ann.find((a) => a.type === 'coverage-layer')?.description;
      results.set(sp.title, { status, layer, project: t.projectName, reason: blocked?.description ?? (r?.error?.message ?? '').split('\n')[0].slice(0, 160) });
    }
  }
};
const reportsDir = join(ROOT, 'reports');
if (existsSync(reportsDir)) {
  for (const f of [join(reportsDir, 'results.json'), ...readdirSync(reportsDir).map((d) => join(reportsDir, d, 'results.json'))]) {
    if (existsSync(f)) collect(JSON.parse(readFileSync(f, 'utf8')), '');
  }
}

const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const statusOf = (t) => {
  // Parametrised titles ("A03 …: …") match every runtime instance; the worst outcome wins.
  const re = new RegExp('^' + t.title.split('…').map(esc).join('.+') + '$');
  const hits = [...results.entries()].filter(([title]) => re.test(title)).map(([, r]) => r);
  const worst = { FAIL: 3, BLOCKED: 2, NOT_RUN: 1, PASS: 0 };
  if (hits.length) return hits.sort((a, b) => worst[b.status] - worst[a.status])[0];
  return t.unconditionalBlock ? { status: 'BLOCKED', reason: 'implemented as an explicit BLOCKED placeholder' } : { status: 'NOT_RUN', reason: '' };
};

// 3. Render
const lines = [];
lines.push('# ASSAB shift-cycle E2E — Business Rules v3.4 traceability', '');
lines.push(`Generated by \`scripts/build-traceability.mjs\`. Business Rules source: \`${rules.source}\` (sha256 \`${rules.sha256.slice(0, 16)}…\`). Acceptance registry: \`traceability/brc34_acceptance_registry.json\` (${registry.scenarios.length} cases).`, '');
lines.push('Coverage layers: **ui-e2e** = asserted through the real React dashboard; **api-assisted** = mobile-only steps through the real Laravel API inside a UI-capable flow; **api-only** = real Laravel API, no browser; **offline** = pure reference arithmetic. An api-only test is never reported as UI E2E.', '');
lines.push(results.size ? 'Result column: latest local `reports/**/results.json`.' : 'Result column: no results.json found — every row is NOT_RUN until the suite is executed.', '');
lines.push('## By test', '', '| Test | File | Layer | Rule ids | Result | Note |', '|---|---|---|---|---|---|');
for (const t of tests) {
  const r = statusOf(t);
  const layer = r.layer && r.layer !== t.layer ? `${r.layer} (this run; ${t.layer})` : t.layer;
  lines.push(`| ${t.title.replace(/\|/g, '\\|')} | \`${t.file}\` | ${layer} | ${t.ids.join(', ') || '—'} | ${r.status} | ${(r.reason ?? '').replace(/\|/g, '\\|')} |`);
}
lines.push('', '## By acceptance case', '', '| AC | BR refs | Expected (registry) | Tests | Results |', '|---|---|---|---|---|');
const rank = { FAIL: 0, BLOCKED: 1, NOT_RUN: 2, PASS: 3 };
for (const sc of registry.scenarios) {
  const covering = tests.filter((t) => t.ids.includes(sc.businessRuleId));
  const counts = {};
  for (const t of covering) { const st = statusOf(t).status; counts[st] = (counts[st] ?? 0) + 1; }
  const best = covering.length ? Object.entries(counts).sort((a, b) => rank[a[0]] - rank[b[0]]).map(([k, v]) => `${k}×${v}`).join(' ') : 'NOT COVERED';
  lines.push(`| ${sc.businessRuleId} | ${sc.businessRuleReferences.join(', ')} | ${String(sc.expectedResult).replace(/\|/g, '\\|').slice(0, 120)} | ${covering.map((t) => t.title.split(' ')[0]).join(', ') || '—'} | ${best} |`);
}
const covered = registry.scenarios.filter((sc) => tests.some((t) => t.ids.includes(sc.businessRuleId))).length;
lines.push('', `Acceptance cases referenced by at least one test: **${covered} / ${registry.scenarios.length}**. "Results" counts every covering test, FAIL first; an AC is only fully evidenced when no covering test fails or is blocked. A PASS in an offline or api-only test does not prove UI behaviour.`, '');
writeFileSync(join(ROOT, 'traceability/TRACEABILITY.md'), lines.join('\n'));
console.log(`traceability/TRACEABILITY.md written: ${tests.length} tests, ${covered}/${registry.scenarios.length} acceptance cases referenced, ${results.size} results merged`);
